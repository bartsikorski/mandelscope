"""High precision reference orbit (Z_{n+1} = Z_n^2 + C) with gmpy2/MPFR.

The Burning Ship (formula "ship"), upright: Z_{n+1} = (|X| + i|Y|)^2 + conj(C), i.e.
X' = X^2 - Y^2 + Re C, Y' = 2|XY| - Im C.

The orbit is computed at MPFR precision but stored in low precision as
"floatexp": a complex mantissa (max(|re|,|im|) in [0.5, 1)) plus a shared
int exponent, so values far below the float64 range are kept exactly enough
for the GPU.  A plain complex128 copy (``zf``) is stored too.

Speed-ups:
  * escape is checked every 16 iterations (|z| grows monotonically after
    escape, so the exact escape index is recovered from the block)
  * periodicity shortcut: once the orbit has converged onto an attracting
    cycle to double precision the rest of the orbit is generated by tiling
    the cycle - a reference at/near a minibrot nucleus is then O(period)
    instead of O(max_iter).
"""
from __future__ import annotations

import math
import time
from dataclasses import dataclass

import numpy as np
import gmpy2
from gmpy2 import mpfr, mpc

EXP_ZERO = -(1 << 20)          # exponent used for exact zero
TINY = 1e-280                  # below this complex128 conversion is not trusted


@dataclass
class ReferenceOrbit:
    re: str                    # reference point C (decimal strings)
    im: str
    prec: int                  # MPFR precision used
    zf: np.ndarray             # complex128 [N] - Z_n rounded (0 where tiny)
    zm: np.ndarray             # complex128 [N] - normalised mantissa
    ze: np.ndarray             # int32 [N]      - exponent (Z = zm * 2**ze)
    escaped: bool              # orbit escaped (len N, last value escaped)
    period: int = 0            # >0 if periodicity shortcut used
    max_iter: int = 0          # iteration limit it was computed for
    state: tuple | None = None  # (z mpc, n) to resume / extend
    elapsed: float = 0.0
    ref_id: int = 0
    cancelled: bool = False    # stopped early (keep_cancelled): resumable with `state`
    resumed_from: int = 0      # length of the orbit this one continued (worker diagnostics)
    z0: tuple | None = None    # Julia references: the starting point (decimal strings); None: 0
    formula: str = "mandelbrot"   # or "ship" (the Burning Ship)
    # Burning Ship: X_n Y_n as floatexp (xym * 2**xye), exact even where one part of Z is far
    # below the other (zf and zm round such a part to 0, and diffabs needs the sign of XY)
    xym: np.ndarray | None = None
    xye: np.ndarray | None = None

    @property
    def length(self) -> int:
        return int(self.zf.shape[0])

    def complete_for(self, max_iter: int) -> bool:
        return self.escaped or self.period > 0 or self.length >= max_iter + 1

    def index(self, n: int) -> int:
        """Where Z_n is stored: a periodic orbit keeps its cycle once, so n wraps back by the
        period past the end (the kernels do the same)."""
        L = self.length
        if n < L or self.period <= 0:
            return n
        return L - self.period + (n - L) % self.period


# ---------------------------------------------------------------------------
# floatexp conversion
# ---------------------------------------------------------------------------

def _frexp_mpfr(x) -> tuple[float, int]:
    if x == 0:
        return 0.0, EXP_ZERO
    e, m = gmpy2.frexp(x)
    return float(m), int(e)


def to_floatexp(vals: list, zc: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Convert a list of gmpy2 mpc values to (zf, zm, ze)."""
    if zc is None:
        zc = np.array([complex(v) for v in vals], dtype=np.complex128)
    re = zc.real
    im = zc.imag
    mx = np.maximum(np.abs(re), np.abs(im))
    _, e = np.frexp(mx)
    e = e.astype(np.int64)
    zm = np.ldexp(re, -e) + 1j * np.ldexp(im, -e)
    zero = mx == 0.0
    tiny = mx < TINY
    zf = zc.copy()
    if np.any(tiny):
        idx = np.nonzero(tiny)[0]
        for i in idx:
            v = vals[i]
            mr, er = _frexp_mpfr(v.real)
            mi, ei = _frexp_mpfr(v.imag)
            if mr == 0.0 and mi == 0.0:
                zm[i] = 0.0
                e[i] = EXP_ZERO
                zf[i] = 0.0
                continue
            ee = max(er, ei)
            zr = math.ldexp(mr, er - ee) if mr != 0.0 else 0.0
            zi = math.ldexp(mi, ei - ee) if mi != 0.0 else 0.0
            zm[i] = complex(zr, zi)
            e[i] = ee
            zf[i] = complex(math.ldexp(zr, max(ee, -1100)), math.ldexp(zi, max(ee, -1100)))
    e[zero & ~tiny] = EXP_ZERO
    return zf, zm, e.astype(np.int32)


def xy_floatexp(vals: list, zc: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Re(z) Im(z) of each value as floatexp (mantissa in [0.5, 1) or 0, int32 exponent),
    from the MPFR values where a part is below the float64 range."""
    with np.errstate(under="ignore"):
        xm, xe = np.frexp(zc.real)
        ym, ye = np.frexp(zc.imag)
    xe = xe.astype(np.int64)
    ye = ye.astype(np.int64)
    bad = (np.abs(zc.real) < TINY) | (np.abs(zc.imag) < TINY)
    for i in np.nonzero(bad)[0]:
        v = vals[i]
        xm[i], xe[i] = _frexp_mpfr(v.real)
        ym[i], ye[i] = _frexp_mpfr(v.imag)
    m, e2 = np.frexp(xm * ym)
    e = xe + ye + e2
    e[m == 0.0] = 0
    return m, e.astype(np.int32)


def _detect_period(zc: np.ndarray, max_p: int = 1 << 21) -> int:
    """Return period p if the tail of the orbit sits on an attracting cycle."""
    n = zc.shape[0]
    if n < 64:
        return 0
    last = zc[-1]
    scale = 1.0 + abs(last)
    lim = min(n // 2, max_p)
    window = zc[n - 1 - lim:n - 1]                  # Z_{n-1-lim} .. Z_{n-2}
    d = np.abs(window - last)
    tol = 4e-15 * scale
    cand = np.nonzero(d <= tol)[0]
    if cand.size == 0:
        return 0
    # smallest p  <->  largest index in window
    for ci in cand[::-1][:8]:
        p = (lim - ci)
        if p < 1 or 2 * p > n - 2:
            continue
        a = zc[n - p:]
        b = zc[n - 2 * p:n - p]
        err = np.max(np.abs(a - b) / (1.0 + np.abs(a)))
        if err > 1e-14:
            continue
        with np.errstate(divide="ignore"):
            loglam = float(np.sum(np.log2(np.maximum(np.abs(2.0 * a), 1e-300))))
        if loglam < -1.0:          # attracting cycle
            return int(p)
    return 0


