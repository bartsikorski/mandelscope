class _Growing:
    """Append-only numpy buffers for the orbit (amortised doubling: O(N) copying in total)."""

    def __init__(self, cap: int = 1 << 14, ship: bool = False):
        self.n = 0
        self.f = np.empty(cap, np.complex128)
        self.m = np.empty(cap, np.complex128)
        self.e = np.empty(cap, np.int32)
        self.names = ("f", "m", "e")
        if ship:
            self.xm = np.empty(cap, np.float64)
            self.xe = np.empty(cap, np.int32)
            self.names = ("f", "m", "e", "xm", "xe")

    def add(self, *arrs):
        k = arrs[0].shape[0]
        if self.n + k > self.f.shape[0]:
            cap = max(2 * self.f.shape[0], self.n + k)
            for name in self.names:
                old = getattr(self, name)
                new = np.empty(cap, old.dtype)
                new[:self.n] = old[:self.n]
                setattr(self, name, new)
        for name, a in zip(self.names, arrs):
            getattr(self, name)[self.n:self.n + k] = a
        self.n += k

    def arrays(self, copy: bool = False):
        sl = slice(0, self.n)
        if copy:
            return tuple(getattr(self, n)[sl].copy() for n in self.names)
        return tuple(getattr(self, n)[sl] for n in self.names)


def _xy(xy) -> dict:
    return dict(xym=xy[0], xye=xy[1]) if xy else {}


def compute_reference(re: str, im: str, prec: int, max_iter: int,
                      bailout: float = 256.0, progress=None, cancelled=None,
                      resume: ReferenceOrbit | None = None,
                      allow_period: bool = True, chunk: int = 8192,
                      partial=None, partial_after: float = 0.5,
                      keep_cancelled: bool = False, z0: tuple | None = None,
                      formula: str = "mandelbrot") -> ReferenceOrbit | None:
    """Compute Z_0..Z_N (N <= max_iter) for C = re + i im, from Z_0 = 0 (the Mandelbrot set) or
    from Z_0 = z0 = (re, im) strings (a point of the Julia set of C).

    progress(fraction) is called periodically; cancelled() -> bool aborts (returns None, or with
    keep_cancelled the orbit so far, marked .cancelled, which can be resumed).  formula "ship":
    the Burning Ship (see the module docstring).  ``resume``
    continues a previous (incomplete) orbit.  partial(ReferenceOrbit) receives the orbit so far
    after `partial_after` seconds and then at doubling intervals, so a long orbit can be used
    (with a lower iteration cap) before it is complete.
    """
    t0 = time.perf_counter()
    ctx = gmpy2.get_context()
    old_prec = ctx.precision
    ctx.precision = prec
    try:
        c = mpc(mpfr(re, prec), mpfr(im, prec))
        ship = formula == "ship"
        if ship:
            c = c.conjugate()
        B2 = mpfr(bailout * bailout)
        sq = gmpy2.square
        norm = gmpy2.norm
        buf = _Growing(max(1 << 14, min(max_iter + 2, 1 << 22)), ship=ship)

        def convert(vals):
            if not ship:
                return to_floatexp(vals)
            zc = np.array([complex(v) for v in vals], dtype=np.complex128)
            return to_floatexp(vals, zc) + xy_floatexp(vals, zc)

        if resume is not None and resume.state is not None:
            z, n = resume.state
            z = mpc(z, precision=prec)
            if ship:
                buf.add(resume.zf, resume.zm, resume.ze, resume.xym, resume.xye)
            else:
                buf.add(resume.zf, resume.zm, resume.ze)
        else:
            z = mpc(0) if z0 is None else mpc(mpfr(z0[0], prec), mpfr(z0[1], prec))
            n = 0
            buf.add(*convert([z]))
        escaped = False
        period = 0
        total = max_iter
        # periodicity checks: every 4 chunks at first, then after every quarter more of the
        # orbit (each check scans up to 2M values: O(N) in total instead of O(N^2))
        next_check = n + 4 * chunk
        next_partial = partial_after
        while n < total:
            cnt = min(chunk, total - n)
            vals = []
            app = vals.append
            done = 0
            while done < cnt:
                blk = 16 if cnt - done >= 16 else cnt - done
                if ship:
                    # (|x| + i|y|)^2 is z^2 when x and y have the same sign, else conj(z^2)
                    for _ in range(blk):
                        w = sq(z)
                        if (z.real < 0) != (z.imag < 0):
                            w = w.conjugate()
                        z = w + c
                        app(z)
                else:
                    for _ in range(blk):
                        z = sq(z) + c
                        app(z)
                done += blk
                if norm(z) > B2:
                    # find first escaping value in the block
                    start = len(vals) - blk
                    for j in range(start, len(vals)):
                        if norm(vals[j]) > B2:
                            del vals[j + 1:]
                            break
                    escaped = True
                    break
            n += len(vals)
            buf.add(*convert(vals))
            if escaped:
                break
            if progress is not None:
                progress(n / max(total, 1))
            if cancelled is not None and cancelled():
                if not keep_cancelled:
                    return None
                zf, zm, ze, *xy = buf.arrays(copy=True)
                r = ReferenceOrbit(re=re, im=im, prec=prec, zf=zf, zm=zm, ze=ze, escaped=False,
                                   max_iter=max_iter, state=(z, n), elapsed=time.perf_counter() - t0,
                                   formula=formula, **_xy(xy))
                r.cancelled = True
                return r
            if allow_period and n > 256 and (n >= next_check or n >= total):
                next_check = n + max(4 * chunk, n // 4)
                # float64 candidates, each confirmed in full precision.  Near a nested minibrot
                # the list starts with multiples of the outer period, so try several: the first
                # one always, more while their periods add up to n/8 (each Newton step costs p
                # iterations)
                budget = n // 8
                for i, p in enumerate(_period_candidates(buf.f[:buf.n])):
                    if i and p > budget:
                        break
                    budget -= p
                    if _confirm_period(z, c, p, prec, ship):
                        period = p
                        break
                if period:
                    break
            if partial is not None and n < total and time.perf_counter() - t0 >= next_partial:
                next_partial = 2.0 * (time.perf_counter() - t0)
                zf, zm, ze, *xy = buf.arrays(copy=True)
                partial(ReferenceOrbit(re=re, im=im, prec=prec, zf=zf, zm=zm, ze=ze, escaped=False,
                                       max_iter=max_iter, state=None, elapsed=time.perf_counter() - t0,
                                       formula=formula, **_xy(xy)))
        # (a periodic orbit is not tiled up to max_iter: the cycle is stored once and the kernels
        # wrap the index - any iteration limit at a minibrot costs no memory)
        arrs = tuple(a.copy() for a in buf.arrays())      # not views of the (larger) buffers
        zf, zm, ze, *xy = arrs
        state = None if (escaped or period) else (z, n)
        return ReferenceOrbit(re=re, im=im, prec=prec, zf=zf, zm=zm, ze=ze,
                              escaped=escaped, period=period, max_iter=max_iter,
                              state=state, elapsed=time.perf_counter() - t0,
                              z0=tuple(z0) if z0 is not None else None, formula=formula, **_xy(xy))
    finally:
        ctx.precision = old_prec
